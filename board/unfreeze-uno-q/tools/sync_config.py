"""Check Linux defaults and App Lab port against the shared MCU deployment header."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def sync(root, write=False):
    header = (root / "sketch/deployment_config.h").read_text(encoding="utf-8")
    values = dict(re.findall(r"^#define UF_(\w+) (.+)$", header, re.MULTILINE))
    keys = ("COMPANION_HOST", "COMPANION_PORT", "CAMERA_HOST", "CAMERA_PORT",
            "BRIDGE_TIMEOUT_MS", "DOOR_CONFIDENCE", "MOTION_CONFIDENCE")
    settings = {key: json.loads(values[key]) for key in keys}
    if not (all(type(settings[k]) is int and 1 <= settings[k] <= 65535
                for k in ("COMPANION_PORT", "CAMERA_PORT"))
            and settings["COMPANION_PORT"] != settings["CAMERA_PORT"]
            and all(0 < settings[k] <= 1 for k in ("DOOR_CONFIDENCE", "MOTION_CONFIDENCE"))
            and settings["BRIDGE_TIMEOUT_MS"] > 0):
        raise ValueError("invalid port, confidence or timeout in deployment_config.h")
    defaults = "# Generated by tools/sync_config.py from sketch/deployment_config.h.\n"
    defaults += "".join(f"{key} = {value!r}\n" for key, value in settings.items())
    manifest = root / "app.yaml"
    text = manifest.read_text(encoding="utf-8")
    updated, count = re.subn(r"(?m)^(ports:\n  - )\d+$",
                             lambda m: m[1] + str(settings["COMPANION_PORT"]), text)
    if count != 1:
        raise ValueError("Expected one companion port in app.yaml")
    for path, expected in ((root / "python/deployment_defaults.py", defaults), (manifest, updated)):
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        if not write:
            raise ValueError(f"{path.name} out of sync; run python3 tools/sync_config.py --write")
        path.write_text(expected, encoding="utf-8")
    return settings


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    print(sync(ROOT, parser.parse_args().write))
